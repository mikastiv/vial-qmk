bool process_record_user(uint16_t keycode, keyrecord_t *record) {
    switch (keycode) {
// ┌───────────────────────────────────────────────────────────┐
// │ l a y e r                                                 │
// └───────────────────────────────────────────────────────────┘
        case QWERTY:
            if (record->event.pressed) {
                set_single_persistent_default_layer(_QWERTY);
            }
            return false;
        case LOWER:
            if (record->event.pressed) {
                layer_on(_LOWER);
                update_tri_layer(_LOWER, _RAISE, _EXTRA);
            } else {
                layer_off(_LOWER);
                update_tri_layer(_LOWER, _RAISE, _EXTRA);
            }
            return false;
        case RAISE:
            if (record->event.pressed) {
                layer_on(_RAISE);
                update_tri_layer(_LOWER, _RAISE, _EXTRA);
            } else {
                layer_off(_RAISE);
                update_tri_layer(_LOWER, _RAISE, _EXTRA);
            }
            return false;
        case EXTRA:
            if (record->event.pressed) {
                layer_on(_EXTRA);
            } else {
                layer_off(_EXTRA);
            }
            return false;
    }
    return true;
}


